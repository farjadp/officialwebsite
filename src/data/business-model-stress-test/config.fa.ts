/** Latin digits to Persian digits, for numbers that sit inside Persian prose. */
export function faDigits(value: string | number): string {
    return String(value).replace(/[0-9]/g, (digit) => "۰۱۲۳۴۵۶۷۸۹"[Number(digit)]);
}

